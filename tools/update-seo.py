#!/usr/bin/env python3
"""Regenerate SEO files for the site.

Writes, for every page pair (Serbian + English):
  - <link rel="canonical"> and <link rel="alternate" hreflang="..."> tags in <head>
  - sitemap.xml and robots.txt in the site root

Run from the repository root after adding or renaming pages, or when the
site moves to its final domain (change BASE_URL below):

    python3 tools/update-seo.py
"""
import os
import re
from datetime import date

BASE_URL = "https://daki-b.github.io/trservices/"

# Serbian page -> matching English page (paths relative to sr/ and en/)
PAGES = {
    "index.html": "index.html",
    "pages/o-nama.html": "pages/about.html",
    "pages/karijere.html": "pages/careers.html",
    "pages/reference.html": "pages/references.html",
    "pages/telefonija.html": "pages/telephony.html",
    "pages/mreza.html": "pages/network.html",
    "pages/multimedija.html": "pages/multimedia.html",
    "pages/security.html": "pages/security.html",
    "pages/hotel.html": "pages/hotel.html",
    "pages/healthcare.html": "pages/healthcare.html",
    "pages/industry.html": "pages/industry.html",
    "pages/koc.html": "pages/koc.html",
    "pages/case-studies/belgrade-airport.html": "pages/case-studies/belgrade-airport.html",
    "pages/case-studies/boge-rubber-plastics.html": "pages/case-studies/boge-rubber-plastics.html",
    "pages/case-studies/cges.html": "pages/case-studies/cges.html",
    "pages/case-studies/cges-telefonija.html": "pages/case-studies/cges-telephony.html",
    "pages/case-studies/cges-video-wall.html": "pages/case-studies/cges-video-wall.html",
    "pages/case-studies/minth.html": "pages/case-studies/minth.html",
    "pages/case-studies/stadion-dubocica.html": "pages/case-studies/stadium-dubocica.html",
    "pages/case-studies/zdravstveni-centar-prokuplje.html": "pages/case-studies/prokuplje-health-centre.html",
}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARK_START = "  <!-- seo:start (generated by tools/update-seo.py) -->\n"
MARK_END = "  <!-- seo:end -->\n"


def url(path):
    return BASE_URL + path


def head_block(own_url, sr_url, en_url, default_url):
    return (
        MARK_START
        + f'  <link rel="canonical" href="{own_url}">\n'
        + f'  <link rel="alternate" hreflang="sr" href="{sr_url}">\n'
        + f'  <link rel="alternate" hreflang="en" href="{en_url}">\n'
        + f'  <link rel="alternate" hreflang="x-default" href="{default_url}">\n'
        + MARK_END
    )


def inject(path, block):
    with open(path, encoding="utf-8") as f:
        html = f.read()
    html = re.sub(re.escape(MARK_START) + r".*?" + re.escape(MARK_END), "", html, flags=re.S)
    html = html.replace("</head>", block + "</head>", 1)
    with open(path, "w", encoding="utf-8") as f:
        f.write(html)


def main():
    entries = []
    for sr, en in PAGES.items():
        sr_url, en_url = url("sr/" + sr), url("en/" + en)
        default_url = url("") if sr == "index.html" else sr_url
        inject(os.path.join(ROOT, "sr", sr), head_block(sr_url, sr_url, en_url, default_url))
        inject(os.path.join(ROOT, "en", en), head_block(en_url, sr_url, en_url, default_url))
        entries.append((sr_url, sr_url, en_url))
        entries.append((en_url, sr_url, en_url))

    today = date.today().isoformat()
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
        '        xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ]
    for loc, sr_url, en_url in entries:
        lines += [
            "  <url>",
            f"    <loc>{loc}</loc>",
            f"    <lastmod>{today}</lastmod>",
            f'    <xhtml:link rel="alternate" hreflang="sr" href="{sr_url}"/>',
            f'    <xhtml:link rel="alternate" hreflang="en" href="{en_url}"/>',
            "  </url>",
        ]
    lines.append("</urlset>")
    with open(os.path.join(ROOT, "sitemap.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    with open(os.path.join(ROOT, "robots.txt"), "w", encoding="utf-8") as f:
        f.write(f"User-agent: *\nAllow: /\n\nSitemap: {url('sitemap.xml')}\n")

    print(f"Updated {len(entries)} pages, sitemap.xml and robots.txt for {BASE_URL}")


if __name__ == "__main__":
    main()
